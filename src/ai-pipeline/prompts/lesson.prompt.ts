export const LESSON_PROMPT_TEMPLATE = `Ты — редактор платформы TechDaily. Спроектируй урок разработчика на русском языке.

Контекст прогресса пользователя (учитывай глубину и мотивацию; не повторяй текст дословно в заголовке урока):
{user_progress_context}

Раздел новостей/ссылок (используй как фактуру для примеров и ссылок):
{items}

Тема дорожки: {topic}
Уровень пользователя в профиле: {skill_level}

ТРЕБОВАНИЯ К ФОРМЕ УРОКА (единый материал ≈100%, три порции):
1) Общий объём темы условно 100 %. Разбей его логически на ТРИ равномерные фазы без дублирования: каждая фаза даёт следующий кусок пути понимания.
2) Последовательность для пользователя: теория фазы 1 → тест из 5 вопросов по фазе 1 → теория фазы 2 → тест → теория фазы 3 → тест → в конце идёт блок flashcards для повторения (после этого пользователь уже в приложении).
3) Поля theory каждой фазы: несколько связных абзацев на русском, спокойный тон, без воды.
4) В КАЖДОЙ фазе ОБЯЗАТЕЛЬНО минимум один пример кода: положи блоки в массив code_examples (каждый элемент — строка с рабочим или учебным кодом; в первой строке комментарием укажи язык, например // TypeScript).
5) Для каждой фазы ровно 5 вопросов в quiz; у каждого вопроса ровно 4 варианта ответа (строки); correct_index целое 0–3.

Остальное:
- title — короткий заголовок на русском (без кликбейта).
- summary — 1 предложение-вступление по сути темы на русском.
- why_it_matters — почему это важно для разработчика уровня {skill_level}.
- source_urls — релевантные URL из входных данных, 1–6 штук.

ВЕРНИ ОДИН JSON-ОБЪЕКТ, без текста до или после и без блоков markdown:
{
  "title": "...",
  "summary": "...",
  "why_it_matters": "...",
  "source_urls": ["..."],
  "phases": [
    {
      "theory": "...",
      "code_examples": ["..."],
      "quiz": [
        {"question":"...","choices":["","","",""],"correct_index":0},
        {"question":"...","choices":["","","",""],"correct_index":1},
        {"question":"...","choices":["","","",""],"correct_index":2},
        {"question":"...","choices":["","","",""],"correct_index":3},
        {"question":"...","choices":["","","",""],"correct_index":0}
      ]
    },
    { "theory": "...", "code_examples": ["..."], "quiz": [ ... exactly 5 ... ] },
    { "theory": "...", "code_examples": ["..."], "quiz": [ ... exactly 5 ... ] }
  ],
  "flashcards": [
    {"question":"...","answer":"..."}
  ]
}

В массиве phases должно быть ровно три элемента. В каждом quiz ровно пять объектов.
В flashcards добавь минимум 4 карточки на русском — для финального переворота в приложении.`;

export function buildLessonPrompt(
  items: string,
  skillLevel: string,
  topic: string,
  userProgressContext: string,
): string {
  const ctx =
    userProgressContext.trim() ||
    'Отдельного отчёта о пройденном нет — дай понятную базовую дорожку по теме.';

  return LESSON_PROMPT_TEMPLATE.replaceAll('{items}', items)
    .replaceAll('{skill_level}', skillLevel)
    .replaceAll('{topic}', topic)
    .replaceAll('{user_progress_context}', ctx);
}
